"""Summary reports of experiment results (mean and bootstrap 95% CI per project)."""

from __future__ import annotations

import logging
from pathlib import Path

import pandas as pd

from sdp.config import Config
from sdp.data.audit import to_markdown
from sdp.eval.stats import bootstrap_ci, scott_knott_esd

logger = logging.getLogger(__name__)

# (metric, threshold_mode, label, higher_is_better)
SUMMARY_METRICS: list[tuple[str, str, str, bool]] = [
    ("roc_auc", "none", "AUC", True),
    ("mcc", "fixed_0.5", "MCC", True),
    ("f1", "fixed_0.5", "F1", True),
    ("recall", "fixed_0.5", "Recall", True),
    ("popt", "none", "Popt", True),
    ("recall_at_20pct_loc", "none", "Recall@20%LOC", True),
    ("necm_15", "fixed_0.5", "NECM15", False),
]


def summarise(metrics: pd.DataFrame, cfg: Config) -> pd.DataFrame:
    """Mean and bootstrap CI over splits, per project and model, plus an ``ALL`` row."""
    e = cfg.evaluation
    rows = []
    for metric, mode, label, _ in SUMMARY_METRICS:
        m = metrics[(metrics["metric"] == metric) & (metrics["threshold_mode"] == mode)]
        groups = [(p, g) for p, g in m.groupby("project", sort=False)] + [("ALL", m)]
        for project, g in groups:
            for model, gm in g.groupby("model", sort=False):
                mean, lo, hi = bootstrap_ci(gm["value"], e.n_resamples, e.confidence, cfg.seed)
                rows.append({"experiment": gm["experiment"].iloc[0], "project": project, "model": model,
                             "metric": label, "mean": mean, "ci_low": lo, "ci_high": hi,
                             "n_splits": int(gm["value"].notna().sum())})  # fmt: skip
    return pd.DataFrame(rows)


def _cell(r) -> str:
    if pd.isna(r["mean"]):
        return "n/a"
    if pd.isna(r["ci_low"]):
        return f"{r['mean']:.3f}"
    return f"{r['mean']:.3f} [{r['ci_low']:.3f}, {r['ci_high']:.3f}]"


def wide_table(summary: pd.DataFrame) -> pd.DataFrame:
    s = summary.assign(cell=summary.apply(_cell, axis=1))
    labels = [lab for _, _, lab, _ in SUMMARY_METRICS]
    wide = s.pivot_table(index=["project", "model"], columns="metric", values="cell", aggfunc="first", sort=False)
    wide = wide[[c for c in labels if c in wide.columns]].reset_index()
    order = list(dict.fromkeys(["ALL", *summary["project"]]))
    wide["_p"] = wide["project"].map(order.index)
    return wide.sort_values(["_p", "model"]).drop(columns="_p")


def skesd_table(metrics: pd.DataFrame) -> pd.DataFrame:
    """Scott-Knott ESD rank of each model per metric, over all splits (1 = best)."""
    rows = []
    for metric, mode, label, higher in SUMMARY_METRICS:
        m = metrics[(metrics["metric"] == metric) & (metrics["threshold_mode"] == mode)]
        wide = m.pivot_table(index="split_id", columns="model", values="value", aggfunc="mean")
        if not higher:
            wide = -wide  # rank so that 1 is always best
        ranks = scott_knott_esd(wide, transform="none").set_index("treatment")["rank"]
        rows.append({"metric": label} | {k: int(v) for k, v in ranks.items()})
    return pd.DataFrame(rows)


def write_baselines_summary(cfg: Config, results: dict[str, pd.DataFrame], path: Path) -> None:
    """Write the Markdown (and CSV) summary of the baseline experiments."""
    parts = [
        "# Trivial baselines",
        "",
        "Generated by `python -m scripts.run_baselines`. Values are the mean over splits with a "
        f"percentile bootstrap {100 * cfg.evaluation.confidence:g}% CI "
        f"({cfg.evaluation.n_resamples:,} resamples, seed {cfg.seed}). `ALL` pools every split "
        "of the protocol. MCC, F1, Recall and NECM15 use a 0.5 threshold (results at the "
        "validation-tuned threshold are in `results/<experiment>/metrics.csv`). Lower NECM15 "
        "is better; for every other metric higher is better.",
        "",
        "Baselines: `manual_up` (risk 1 / max(LOC, 1)) and `manual_down` (risk LOC), both "
        "min-max normalised on training data; `all_defective` (probability 1.0 for every "
        "class); `majority` (DummyClassifier, prior strategy). Baselines always use raw "
        "features (no preprocessing). Effort-aware metrics rank by predicted "
        "risk density (probability / LOC); a constant predictor (`all_defective`, `majority`) "
        "therefore inspects the smallest classes first, i.e. it behaves like the ManualUp "
        "effort baseline, whereas `manual_down` inspects the largest classes first.",
        "",
        "Per-project CIs under the time-aware protocol rest on only 2-4 release pairs and are "
        "indicative only.",
        "",
    ]
    all_summaries = []
    for exp, metrics in results.items():
        summary = summarise(metrics, cfg)
        all_summaries.append(summary)
        n_splits = metrics["split_id"].nunique()
        parts += [
            f"## {exp}",
            "",
            f"{n_splits} splits.",
            "",
            to_markdown(wide_table(summary)),
            "",
            "Scott-Knott ESD ranks over all splits (1 = best; NECM15 ranked with lower = better):",
            "",
            to_markdown(skesd_table(metrics)),
            "",
        ]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(parts), encoding="utf-8")
    pd.concat(all_summaries).to_csv(path.with_suffix(".csv"), index=False)
    logger.info("Wrote %s", path)
